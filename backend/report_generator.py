"""Demo Report Generator for Indian Stock Research Platform.

Returns a structured prototype research report clearly labeled as demo data.
AI agents and live financial data integrations will populate this in future phases.
"""

from datetime import datetime, timezone
from schemas import BullBearDebate, ReportSection, ResearchReport
from database import get_stock_by_symbol


def generate_demo_report(symbol: str) -> ResearchReport:
    stock = get_stock_by_symbol(symbol)
    company_name = stock["company_name"] if stock else f"{symbol.upper()} Equity"
    exchange = stock["exchange"] if stock else "NSE"
    sector = stock.get("sector") or "Diversified"
    description = stock.get("description") if stock else f"Company listed under ticker {symbol}."

    now_iso = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    return ResearchReport(
        report_id=f"DEMO-RPT-{symbol.upper()}-{int(datetime.now().timestamp())}",
        symbol=symbol.upper(),
        company_name=company_name,
        exchange=exchange,
        generated_at=now_iso,
        status="demo",
        is_prototype_demo=True,
        disclaimer=(
            "DEMO RESEARCH REPORT: This synthesis is generated by the prototype backend for interface "
            "and workflow validation. It does not reflect verified financial data, active multi-agent debates, "
            "or investment advisory recommendations."
        ),
        business_overview=ReportSection(
            title="Business Overview",
            status="prototype_demo",
            summary=(
                f"{company_name} is an established company in the {sector} sector. "
                f"{description} The business model is driven by core market distribution across Indian and global markets."
            ),
            key_points=[
                f"Core sector operating footprint: {sector}",
                f"Primary listing: {exchange} (India)",
                "Revenue streams characterized by contracted enterprise accounts and domestic consumer reach.",
                "Positioned among peer group benchmarks for capital allocation discipline."
            ]
        ),
        financial_analysis=ReportSection(
            title="Financial Analysis (Demo Prototype)",
            status="prototype_demo",
            summary=(
                "Illustrative financial baseline indicating standard metrics monitored during comprehensive research. "
                "Real historical audited financial statements and ratios will be integrated in subsequent phases."
            ),
            key_points=[
                "Operating Margins: Historically maintained resilient margin buffers through input-cost inflation cycles.",
                "Working Capital Cycle: Reflects normalized inventory days and conservative receivables management.",
                "Leverage & Solvency: Debt-to-Equity profile consistent with sectoral median levels.",
                "Cash Flow Conversion: Stable operating cash flows supporting capital expenditure pipelines."
            ]
        ),
        growth_prospects=ReportSection(
            title="Growth Catalysts & Expansion",
            status="prototype_demo",
            summary=(
                "Macroeconomic tailwinds in Indian domestic consumption, digital infrastructure, and industrial capacity "
                "form the broader backdrop for projected medium-term growth."
            ),
            key_points=[
                "Expansion into tier-2/tier-3 urban clusters and enhanced omnichannel distribution.",
                "Adoption of advanced automated manufacturing and cloud-first enterprise architectures.",
                "Selective strategic M&A opportunities in adjacent synergistic verticals.",
                "Favorable policy incentives under Make in India and sectoral performance-linked initiatives."
            ]
        ),
        valuation=ReportSection(
            title="Valuation Framework",
            status="prototype_demo",
            summary=(
                "Multi-model valuation methodology (DCF, Price-to-Earnings bands, and EV/EBITDA peer multiples). "
                "Metrics below are illustrative placeholders until live feeds are connected."
            ),
            key_points=[
                "Trailing & Forward P/E multiples trade within historical 5-year cyclical bands.",
                "DCF assumptions reflect normalized cost of capital (WACC) aligned with Indian 10Y Sovereign Yields.",
                "Peer-relative comparative discount/premium justified by return on capital employed (ROCE) differentials."
            ]
        ),
        risks=ReportSection(
            title="Risk Factors & Sensitivities",
            status="prototype_demo",
            summary=(
                "Identified operational, market, regulatory, and execution risks requiring continuous multi-agent monitoring."
            ),
            key_points=[
                "Macro Risk: Volatility in crude oil, global interest rates, and currency fluctuations (USD/INR).",
                "Regulatory Risk: Shifts in domestic compliance standards, tariffs, or taxation frameworks.",
                "Competitive Risk: Emerging disruptive technologies and aggressive price competition from new entrants.",
                "Execution Risk: Delays or cost overruns in major ongoing capital expenditure programs."
            ]
        ),
        bull_vs_bear=BullBearDebate(
            bull_case=[
                "Strong competitive moat and high brand recall across core Indian consumer/enterprise demographics.",
                "Disciplined balance sheet with sufficient liquidity to withstand adverse cyclical downturns.",
                "High earnings visibility supported by a robust order pipeline or recurring subscription revenue.",
                "Beneficiary of formalization of the Indian economy and structural credit growth."
            ],
            bear_case=[
                "Potential margin compression if raw material or wage inflation persists above quarterly guidance.",
                "Elevated valuation multiples leave limited margin of safety against unexpected execution slips.",
                "Intensifying competition in key growth segments may require defensive marketing expenditures.",
                "Vulnerability to global macroeconomic deceleration affecting export or overseas subsidiary earnings."
            ],
            critical_swing_factors=[
                "Pace of quarterly margin expansion over the upcoming two financial quarters.",
                "Capital allocation efficiency for newly commissioned greenfield/brownfield facilities.",
                "Management commentary regarding demand trends in rural versus urban Indian markets."
            ]
        ),
        final_assessment=ReportSection(
            title="Final Multi-Agent Assessment Synthesis",
            status="prototype_demo",
            summary=(
                "Synthesized view balancing the bull thesis against prevailing downside risks. "
                "In future releases, this synthesis will be generated through an autonomous debate loop between "
                "dedicated Bull, Bear, and Risk Arbitrageur agents."
            ),
            key_points=[
                "Strategic Positioning: High-quality franchise with durable sectoral positioning.",
                "Near-Term Outlook: Neutral-to-Constructive pending resolution of input cost pressures.",
                "Next Steps: Integration of automated live agent debate engines and real-time filings ingestion."
            ]
        )
    )
